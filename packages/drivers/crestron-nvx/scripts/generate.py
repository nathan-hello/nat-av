"""Generate reviewed HTTPS bindings from the pinned NuGet compiler XML docs."""
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

root = Path(__file__).resolve().parents[1]
package = "Crestron.SimplSharp.SDK.ProgramLibrary"
# The restore-only project pins the SDK version; the explicit root
# `pnpm run setup` restores it into sdk/packages (NuGet lowercases folder names).
# This script itself never touches the network.
reference = next(r for r in ET.parse(root / "sdk/CrestronSdk.csproj").iter("PackageReference")
                 if r.get("Include") == package)
version = reference.get("Version")
lib = root / "sdk/packages" / package.lower() / version / "lib/net6.0"
if not lib.is_dir():
    sys.exit(f"Missing {lib}. Run `pnpm run setup` from the workspace root first.")
prefix = "Crestron.SimplSharpPro.DM.Streaming."


def members(assembly):
    return {e.attrib["name"]: e for e in
            ET.parse(lib / (assembly + ".xml")).findall("./members/member")}


models = members("Crestron.SimplSharpPro.DM")
controls = members("SimplSharpPro")
# Reviewed subset of DeviceSpecific.AudioSource wire values. Feedback-only
# constants and SDK names without a documented REST spelling are excluded.
wire = ("AudioFollowsVideo", "Input1", "Input2", "AnalogAudio",
        "PrimaryStreamAudio", "SecondaryStreamAudio")
profiles = {}
for sku in ("350", "351", "352", "360", "363"):
    for suffix in ("", "C"):
        product = sku + suffix
        symbol = "DmNvx" + product
        if "T:" + prefix + symbol not in models:
            raise ValueError("Missing SDK type " + symbol)
        sources = []
        for value in wire:
            member = controls["F:" + prefix + "DmNvxControl.eAudioSource." + value]
            summary = member.find("summary")
            text = " ".join("".join(summary.itertext()).split())
            refs = {s.get("cref") for s in summary.iter("see")}
            if "not supported by" in text and (
                "!:" + symbol in refs or "!:" + "DmNvx" + sku in refs or
                ("DM-NVX-36x" in text and sku.startswith("36"))
            ):
                continue
            sources.append(value)
        # Hardware overlay from the Crestron model manuals (SDK control-property
        # summaries alone omit the 363 even though its hardware supports Dante).
        profiles["DM-NVX-" + product] = {"audioSources": sources, "dante": sku in ("352", "363")}

dest = root / "generated.ts"
dest.write_text("// Generated by scripts/generate.py; SDK " + version + ".\n"
                + "export const profiles = " + json.dumps(profiles, indent=2) + " as const;\n")
